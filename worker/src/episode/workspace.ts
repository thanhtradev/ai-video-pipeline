import { cp, mkdir, readdir, readFile, rename, stat, symlink, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

// The episode workspace (docs/episode-pipeline.md §6): what the episode agent sees and may change.
// Layout: CLAUDE.md, brief.md, [feedback.md], FILES.md (index, since the agent has no search tool),
// kit/ (the channel kit and the reference episodes, read-only), src/ (worker entry, compositions and
// time helpers; the agent writes src/episode/), sfx/generate-sfx.mjs (the agent writes), public/
// (voice.wav; the SFX land in public/sfx), node_modules → the repo's packages, tmp/ (TMPDIR).

const REMOTION_DIR = fileURLToPath(new URL('../../../remotion/', import.meta.url));
const TEMPLATE_DIR = join(REMOTION_DIR, 'episode');
const KIT_DIR = join(REMOTION_DIR, 'src', 'tiktok2');
const NODE_MODULES = fileURLToPath(new URL('../../../node_modules', import.meta.url));
/** The kit parts the agent builds on: shared kit (ep1), the reference episodes, QA, SFX synthesis. */
const KIT_PARTS = ['ep1', 'ep2', 'ep3', 'ep5', 'qa', 'sfx', 'env.d.ts'];
/** Paths the agent may write, relative to the workspace. */
export const AGENT_WRITABLE = ['src/episode', 'sfx'] as const;
export const GATES_SCRIPT = join(REMOTION_DIR, 'scripts', 'episode-gates.mjs');

export interface WorkspaceSources {
  /** script.md of the approved script job. */
  scriptMarkdown: string;
  /** timing job folder with timing.json, captions.json and voice.wav. */
  timingDir: string;
  /** Revision: the previous workspace (its episode code and SFX script are copied) and the notes. */
  revision?: { previousWorkspace: string; feedback: string } | undefined;
}

async function listFiles(dir: string, root: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) => {
      const path = join(dir, entry.name);
      return entry.isDirectory() ? listFiles(path, root) : Promise.resolve([relative(root, path)]);
    }),
  );
  return nested.flat().sort();
}

/** FILES.md: every kit and source file with its size, so the agent can Read by path. */
async function fileIndex(ws: string): Promise<string> {
  const files = [
    ...(await listFiles(join(ws, 'kit'), ws)),
    ...(await listFiles(join(ws, 'src'), ws)),
  ];
  const rows = await Promise.all(
    files.map(async (file) => `- ${file} (${(await stat(join(ws, file))).size} bytes)`),
  );
  return `# Files\n\nGenerated by the worker. Read files by these paths.\n\n${rows.join('\n')}\n`;
}

export async function prepareWorkspace(ws: string, sources: WorkspaceSources): Promise<void> {
  await mkdir(ws, { recursive: true });
  await cp(TEMPLATE_DIR, ws, { recursive: true });
  // Kept as AGENT.md in the repo so sessions working on the repo do not load it as their CLAUDE.md.
  await rename(join(ws, 'AGENT.md'), join(ws, 'CLAUDE.md'));
  await Promise.all(
    KIT_PARTS.map((part) => cp(join(KIT_DIR, part), join(ws, 'kit', part), { recursive: true })),
  );
  await mkdir(join(ws, 'src', 'data'), { recursive: true });
  await mkdir(join(ws, 'public', 'sfx'), { recursive: true });
  await mkdir(join(ws, 'tmp'), { recursive: true });
  for (const name of ['timing.json', 'captions.json']) {
    await cp(join(sources.timingDir, name), join(ws, 'src', 'data', name));
  }
  await cp(join(sources.timingDir, 'voice.wav'), join(ws, 'public', 'voice.wav'));
  await writeFile(join(ws, 'brief.md'), sources.scriptMarkdown);
  if (sources.revision) {
    const previous = sources.revision.previousWorkspace;
    for (const part of AGENT_WRITABLE) {
      await cp(join(previous, part), join(ws, part), { recursive: true, force: true });
    }
    await writeFile(join(ws, 'feedback.md'), `# Feedback\n\n${sources.revision.feedback}\n`);
  }
  await symlink(NODE_MODULES, join(ws, 'node_modules'));
  await writeFile(join(ws, 'FILES.md'), await fileIndex(ws));
}

/** Text files the agent wrote, for the secret scan and the job outputs. */
export async function agentFiles(ws: string): Promise<string[]> {
  const lists = await Promise.all(AGENT_WRITABLE.map((part) => listFiles(join(ws, part), ws)));
  return lists.flat();
}

/** True when any agent-written file contains one of the given secret values. */
export async function containsSecret(ws: string, secrets: readonly string[]): Promise<string[]> {
  const values = secrets.filter((s) => s.length >= 16);
  if (values.length === 0) return [];
  const files = await agentFiles(ws);
  const hits = await Promise.all(
    files.map(async (file) => {
      const text = await readFile(join(ws, file), 'utf8');
      return values.some((v) => text.includes(v)) ? [file] : [];
    }),
  );
  return hits.flat();
}
