import { existsSync } from 'node:fs';
import { cp, mkdir, readdir, readFile, rm, stat, symlink, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveSelection, type ResolvedSelection, type Selection } from './catalog.js';

// The episode workspace (docs/episode-pipeline.md §6): what the episode agent sees and may change.
// Layout: CLAUDE.md (the base AGENT.md with the selected kit's and character set's AGENT.md spliced
// in), brief.md, rules.md (owner's rules, D-059), [feedback.md], FILES.md (index, since the agent has
// no search tool), kit/ (read-only: the rig, the selected kit, character set and reference episode
// at their remotion/src paths, plus kit/active/<name>.ts re-exports so episode code never names a
// kit), src/ (worker entry, compositions and time helpers; the agent writes src/episode/),
// sfx/generate-sfx.mjs (the agent writes), public/ (voice.wav; the SFX land in public/sfx),
// node_modules → the repo's packages, tmp/ (TMPDIR).

const REMOTION_DIR = fileURLToPath(new URL('../../../remotion/', import.meta.url));
const TEMPLATE_DIR = join(REMOTION_DIR, 'episode');
const KIT_SRC = join(REMOTION_DIR, 'src');
const NODE_MODULES = fileURLToPath(new URL('../../../node_modules', import.meta.url));
/** Placeholders in remotion/episode/AGENT.md filled from the selected kit and character set. */
const KIT_MARK = '<!-- KIT -->';
const CHARACTERS_MARK = '<!-- CHARACTERS -->';
const REFERENCE_MARK = '<!-- REFERENCE -->';
/** Unit tests and type shims of the kit are not copied into the agent's workspace. */
const isKitSource = (path: string) => !/\.test\.tsx?$/.test(path);
/** Paths the agent may write, relative to the workspace. */
export const AGENT_WRITABLE = ['src/episode', 'sfx'] as const;
export const GATES_SCRIPT = join(REMOTION_DIR, 'scripts', 'episode-gates.mjs');
export const RENDER_SCRIPT = join(REMOTION_DIR, 'scripts', 'episode-render.mjs');
/** Remotion's Chrome, written by `npx remotion browser ensure` in remotion/. The sandboxed gates and
 * renders have no network, so they cannot download it themselves. */
export const CHROME_VERSION_FILE = join(
  REMOTION_DIR,
  'node_modules',
  '.remotion',
  'chrome-headless-shell',
  'VERSION',
);
export const chromeInstalled = (): boolean => existsSync(CHROME_VERSION_FILE);

export interface WorkspaceSources {
  /** script.md of the approved script job. */
  scriptMarkdown: string;
  /** timing job folder with timing.json, captions.json and voice.wav. */
  timingDir: string;
  /** rules.md: the owner's channel rules (D-059). */
  rulesMarkdown: string;
  /** Revision: the previous workspace (its episode code and SFX script are copied) and the notes. */
  revision?: { previousWorkspace: string; feedback: string } | undefined;
  /** Kit and character set of the clip (catalog slugs); the catalog defaults when absent. */
  selection?: Selection | undefined;
}

async function listFiles(dir: string, root: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) => {
      const path = join(dir, entry.name);
      return entry.isDirectory() ? listFiles(path, root) : Promise.resolve([relative(root, path)]);
    }),
  );
  return nested.flat().sort();
}

/** FILES.md: every kit and source file with its size, so the agent can Read by path. */
async function fileIndex(ws: string): Promise<string> {
  const files = [
    ...(await listFiles(join(ws, 'kit'), ws)),
    ...(await listFiles(join(ws, 'src'), ws)),
  ];
  const rows = await Promise.all(
    files.map(async (file) => `- ${file} (${(await stat(join(ws, file))).size} bytes)`),
  );
  return `# Files\n\nGenerated by the worker. Read files by these paths.\n\n${rows.join('\n')}\n`;
}

/** kit/active/<name>.ts: one re-export per catalog module, so episode code imports `../../kit/active/theme` etc. */
async function writeActiveModules(ws: string, modules: Readonly<Record<string, string>>) {
  const dir = join(ws, 'kit', 'active');
  await mkdir(dir, { recursive: true });
  await Promise.all(
    Object.entries(modules).map(([name, mod]) =>
      writeFile(join(dir, `${name}.ts`), `export * from '../${mod}';\n`),
    ),
  );
}

async function readDocs(paths: readonly string[]): Promise<string> {
  const texts = await Promise.all(
    paths.map(async (path) => {
      const file = join(KIT_SRC, path);
      return existsSync(file) ? (await readFile(file, 'utf8')).trim() : '';
    }),
  );
  return texts.filter(Boolean).join('\n\n');
}

/** CLAUDE.md = the base AGENT.md with the kit's and the character set's sections spliced in. */
async function assembleClaudeMd(ws: string, selection: ResolvedSelection): Promise<void> {
  const base = await readFile(join(ws, 'AGENT.md'), 'utf8');
  for (const mark of [KIT_MARK, CHARACTERS_MARK, REFERENCE_MARK]) {
    if (!base.includes(mark)) throw new Error(`remotion/episode/AGENT.md lacks ${mark}`);
  }
  const text = base
    .replaceAll(REFERENCE_MARK, `kit/${selection.referenceEpisode}/`)
    .replace(KIT_MARK, await readDocs(selection.kitDocs))
    .replace(CHARACTERS_MARK, await readDocs(selection.characterDocs));
  await writeFile(join(ws, 'CLAUDE.md'), text);
  // Kept as AGENT.md in the repo so sessions working on the repo do not load it as their CLAUDE.md.
  await rm(join(ws, 'AGENT.md'));
}

export async function prepareWorkspace(
  ws: string,
  sources: WorkspaceSources,
): Promise<ResolvedSelection> {
  const selection = resolveSelection(sources.selection ?? {});
  await mkdir(ws, { recursive: true });
  await cp(TEMPLATE_DIR, ws, { recursive: true });
  await assembleClaudeMd(ws, selection);
  for (const dir of selection.dirs) {
    await mkdir(dirname(join(ws, 'kit', dir)), { recursive: true });
    await cp(join(KIT_SRC, dir), join(ws, 'kit', dir), { recursive: true, filter: isKitSource });
  }
  await writeActiveModules(ws, selection.modules);
  await mkdir(join(ws, 'src', 'data'), { recursive: true });
  await mkdir(join(ws, 'public', 'sfx'), { recursive: true });
  await mkdir(join(ws, 'tmp'), { recursive: true });
  for (const name of ['timing.json', 'captions.json']) {
    await cp(join(sources.timingDir, name), join(ws, 'src', 'data', name));
  }
  await cp(join(sources.timingDir, 'voice.wav'), join(ws, 'public', 'voice.wav'));
  await writeFile(join(ws, 'brief.md'), sources.scriptMarkdown);
  await writeFile(join(ws, 'rules.md'), sources.rulesMarkdown);
  if (sources.revision) {
    const previous = sources.revision.previousWorkspace;
    for (const part of AGENT_WRITABLE) {
      await cp(join(previous, part), join(ws, part), { recursive: true, force: true });
    }
    await writeFile(join(ws, 'feedback.md'), `# Feedback\n\n${sources.revision.feedback}\n`);
  }
  await symlink(NODE_MODULES, join(ws, 'node_modules'));
  await writeFile(join(ws, 'FILES.md'), await fileIndex(ws));
  return selection;
}

/** Text files the agent wrote, for the secret scan and the job outputs. */
export async function agentFiles(ws: string): Promise<string[]> {
  const lists = await Promise.all(AGENT_WRITABLE.map((part) => listFiles(join(ws, part), ws)));
  return lists.flat();
}

/** True when any agent-written file contains one of the given secret values. */
export async function containsSecret(ws: string, secrets: readonly string[]): Promise<string[]> {
  const values = secrets.filter((s) => s.length >= 16);
  if (values.length === 0) return [];
  const files = await agentFiles(ws);
  const hits = await Promise.all(
    files.map(async (file) => {
      const text = await readFile(join(ws, file), 'utf8');
      return values.some((v) => text.includes(v)) ? [file] : [];
    }),
  );
  return hits.flat();
}

/** A copy of an approved workspace to render from; node_modules stays a symlink. */
export async function copyWorkspace(from: string, to: string): Promise<void> {
  await cp(from, to, { recursive: true, verbatimSymlinks: true });
  await mkdir(join(to, 'tmp'), { recursive: true });
}
